-- 001_log_tables.sql — the template's append-only log tables (log_ = audit / telemetry).
--
-- ⭐ The SQL migration is the SOURCE OF TRUTH for the schema; the Sequelize models in
-- database/models/ mirror it. A table no migration created is a boot failure (schema guard).
-- Runs ONCE (database/migrate.js records it in log_migrations with a checksum) — never edit an
-- applied migration; add a new numbered file instead.
-- search_path is set to the project schema by the runner: never name a schema in here.

CREATE TABLE log_messages (
    uuid             uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    rolling_id       integer       GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    server_start_on  timestamptz   NOT NULL,
    report_on        timestamptz   NOT NULL,
    report_by        varchar(255)  NOT NULL,
    level            varchar(10)   NOT NULL DEFAULT 'info'
                     CONSTRAINT log_messages_level_check CHECK (level IN ('info', 'warning', 'error')),
    messages         text          NOT NULL,
    created_at       timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX log_messages_created_at_idx ON log_messages (created_at);
COMMENT ON TABLE log_messages IS 'Append-only application log (log() with logging.message.log_to_database on).';

CREATE TABLE log_requests (
    uuid              uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    rolling_id        integer       GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    request_at        timestamptz   NOT NULL,
    request_ip        varchar(64),
    request_to        text          NOT NULL,
    request_protocol  varchar(10),
    request_method    varchar(10)   NOT NULL,
    response_status   integer,
    duration_ms       real,
    request_header    jsonb,
    request_body      jsonb,
    created_at        timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX log_requests_created_at_idx ON log_requests (created_at);
COMMENT ON TABLE log_requests IS 'Append-only request log. Headers/body only when logging.request.log_headers/log_body are on, and always redacted.';
