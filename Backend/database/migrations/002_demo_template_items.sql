CREATE TABLE mst_template_items (
    uuid        uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    rolling_id  integer       GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    name        varchar(200)  NOT NULL
                CONSTRAINT mst_template_items_name_check CHECK (btrim(name) <> ''),
    summary     text          NOT NULL DEFAULT '',
    status      varchar(20)   NOT NULL DEFAULT 'draft'
                CONSTRAINT mst_template_items_status_check CHECK (status IN ('draft', 'active', 'archived')),
    priority    varchar(20)   NOT NULL DEFAULT 'medium'
                CONSTRAINT mst_template_items_priority_check CHECK (priority IN ('low', 'medium', 'high')),
    created_at  timestamptz   NOT NULL DEFAULT now(),
    updated_at  timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX mst_template_items_updated_at_idx ON mst_template_items (updated_at DESC);
COMMENT ON TABLE mst_template_items IS 'Demo feature (template example) — replace with your own domain.';
