-- 003_auth_users.sql — accounts for the optional auth module (app/modules/auth/).
-- Local users (username + bcrypt hash) and people who signed in with Oteracount (keyed by `sub`)
-- live in ONE table; the config root account is NOT here (it works without a database).
-- Not using auth at all? Delete this file before the first db:migrate (with the module).
-- search_path is set to the project schema by the runner: never name a schema in here.

CREATE TABLE mst_users (
    uuid            uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    rolling_id      integer       GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    username        varchar(100)  UNIQUE
                    CONSTRAINT mst_users_username_check CHECK (username IS NULL OR username ~ '^[a-z0-9._-]{2,100}$'),
    display_name    varchar(200)  NOT NULL DEFAULT '',
    password_hash   varchar(100),
    oteracount_sub  varchar(255)  UNIQUE,
    role            varchar(50)   NOT NULL DEFAULT 'user',
    is_active       boolean       NOT NULL DEFAULT true,
    last_login_at   timestamptz,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    -- every account can sign in SOME way: a local password or an Oteracount identity
    CONSTRAINT mst_users_login_check CHECK (password_hash IS NOT NULL OR oteracount_sub IS NOT NULL),
    CONSTRAINT mst_users_local_check CHECK (password_hash IS NULL OR username IS NOT NULL)
);
COMMENT ON TABLE mst_users IS 'Accounts for the auth module: local (username + bcrypt password_hash) and/or Oteracount (oteracount_sub). Roles map to permissions in config auth.roles.';
